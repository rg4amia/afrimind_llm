import hashlib
import random
import re
from pathlib import Path

from bekami.tokenizer import SPECIAL_TOKENS

CODE_EXT = {
    ".py", ".php", ".js", ".jsx", ".ts", ".tsx", ".vue", ".dart", ".java", ".kt", ".swift",
    ".go", ".rs", ".c", ".h", ".cpp", ".hpp", ".cs", ".rb", ".sql", ".sh", ".html", ".css",
    ".scss", ".md", ".yaml", ".yml", ".toml", ".dockerfile",
}
SKIP_DIRS = {
    ".git", "node_modules", "vendor", "venv", ".venv", "dist", "build", "__pycache__",
    ".next", ".idea", ".gradle", "target", "storage", "coverage",
}
SKIP_NAMES = {
    "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "composer.lock", "poetry.lock",
    "Cargo.lock", "Pipfile.lock",
}
GENERATED_MARKERS = ("auto-generated", "autogenerated", "do not edit", "generated by", "@generated")
SECRET_PATTERNS = [
    re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----"),
    re.compile(r"AKIA[0-9A-Z]{16}"),
    re.compile(r"gh[pousr]_[A-Za-z0-9]{30,}"),
    re.compile(r"sk-[A-Za-z0-9]{32,}"),
    re.compile(r"(?i)(api[_-]?key|secret|passw(or)?d|token)\s*[:=]\s*['\"][A-Za-z0-9/+_\-]{16,}['\"]"),
]

def iter_repo_files(repo_dir):
    for path in sorted(Path(repo_dir).rglob("*")):
        rel = path.relative_to(repo_dir)
        if not path.is_file() or any(p in SKIP_DIRS for p in rel.parts[:-1]):
            continue
        if path.name in SKIP_NAMES or path.suffix.lower() not in CODE_EXT:
            continue
        yield path, rel.as_posix()

def clean_file(text):
    """Renvoie le texte nettoyé, ou None si le fichier doit être écarté."""
    if not 20 <= len(text) <= 1_000_000:
        return None
    lines = text.splitlines()
    if not lines or max(map(len, lines)) > 1000 or len(text) / len(lines) > 100:
        return None
    if sum(c.isalnum() for c in text) / len(text) < 0.25:
        return None
    head = "\n".join(lines[:5]).lower()
    if any(m in head for m in GENERATED_MARKERS):
        return None
    if any(p.search(text) for p in SECRET_PATTERNS):
        return None
    # un fichier ne doit pas pouvoir injecter un token spécial dans le flux d'entraînement
    for tok in SPECIAL_TOKENS:
        text = text.replace(tok, "")
    return text

def order_files(rel_paths):
    # README et fichiers de config d'abord, puis par dossier : les fichiers liés restent voisins
    def key(p):
        name = p.rsplit("/", 1)[-1].lower()
        return (0 if name.startswith("readme") else 1, p)
    return sorted(rel_paths, key=key)

class Decontaminator:
    """Écarte les fichiers qui partagent une fenêtre de `n` mots avec un jeu d'évaluation
    (fichiers .txt placés dans `decontam_dir`)."""
    def __init__(self, decontam_dir="data/decontam", n=10):
        self.n = n
        self.hashes = set()
        for path in Path(decontam_dir).glob("*.txt"):
            self.hashes |= self._windows(path.read_text(encoding="utf-8", errors="ignore"))

    def _windows(self, text):
        w = text.split()
        return {hash(" ".join(w[i:i + self.n])) for i in range(max(0, len(w) - self.n + 1))}

    def is_contaminated(self, text):
        return bool(self.hashes) and not self.hashes.isdisjoint(self._windows(text))

def fim_ids(tok, text, rng, rate=0.5):
    """Applique le fill-in-the-middle (formats PSM et SPM à parts égales) à `rate` des fichiers."""
    sp = tok.special
    if len(text) < 2 or rng.random() >= rate:
        return tok.encode(text)
    a, b = sorted(rng.sample(range(len(text) + 1), 2))
    pre, mid, suf = (tok.encode(s) if s else [] for s in (text[:a], text[a:b], text[b:]))
    if rng.random() < 0.5:
        return [sp["<fim_prefix>"]] + pre + [sp["<fim_suffix>"]] + suf + [sp["<fim_middle>"]] + mid
    return [sp["<fim_prefix>"], sp["<fim_suffix>"]] + suf + [sp["<fim_middle>"]] + pre + mid

def repo_document_ids(tok, repo_name, files, rng, fim_rate=0.5):
    """files : liste de (chemin relatif, texte). Un dépôt devient un seul document."""
    sp = tok.special
    ids = [sp["<repo_name>"]] + tok.encode(repo_name)
    for rel, text in files:
        ids += [sp["<file_sep>"]] + tok.encode(rel + "\n") + fim_ids(tok, text, rng, fim_rate)
    return ids + [tok.eos_id]

def is_validation(name, percent=2):
    # la découpe se fait par dépôt : aucun fichier d'un même dépôt n'est à la fois en train et en val
    return int(hashlib.sha1(name.encode()).hexdigest(), 16) % 100 < percent

def make_rng(seed=0):
    return random.Random(seed)

def iter_corpus(raw_dir="data/raw", decontam_dir="data/decontam"):
    """Parcourt data/raw/repos/<dépôt>/ et data/raw/*.txt. Renvoie (nom, is_repo, [(chemin, texte)]),
    après nettoyage, dédoublonnage exact et décontamination."""
    raw = Path(raw_dir)
    seen, decontam = set(), Decontaminator(decontam_dir)
    stats = dict(kept=0, dropped_clean=0, dropped_dup=0, dropped_contam=0)

    def accept(text):
        text = clean_file(text)
        if text is None:
            stats["dropped_clean"] += 1
            return None
        digest = hashlib.sha1(" ".join(text.split()).encode()).hexdigest()
        if digest in seen:
            stats["dropped_dup"] += 1
            return None
        if decontam.is_contaminated(text):
            stats["dropped_contam"] += 1
            return None
        seen.add(digest)
        stats["kept"] += 1
        return text

    for repo in sorted(p for p in (raw / "repos").glob("*") if p.is_dir()):
        files = []
        for path, rel in iter_repo_files(repo):
            text = accept(path.read_text(encoding="utf-8", errors="ignore"))
            if text is not None:
                files.append((rel, text))
        if files:
            order = {rel: i for i, rel in enumerate(order_files([r for r, _ in files]))}
            yield repo.name, True, sorted(files, key=lambda f: order[f[0]])
    for path in sorted(raw.glob("*.txt")):
        text = accept(path.read_text(encoding="utf-8", errors="ignore"))
        if text is not None:
            yield path.name, False, [(path.name, text)]
    print("Corpus :", stats)
